import { parsePriceValue } from "../lib/collection-filters.mjs";

function enrich(product) {
  const colors = product.colors || product.swatches || [];
  return {
    ...product,
    priceValue: product.priceValue ?? parsePriceValue(product.price),
    availability: product.availability || "in_stock",
    stock: Number.isInteger(product.stock) ? product.stock : null,
    sizes: product.sizes || ["Free size"],
    colors,
    swatches: product.swatches || colors,
    collections: product.collections || [],
    createdAt: product.createdAt || "2026-09-01",
  };
}

